import { Check, Copy, Download } from 'lucide-react';
import QRCode from 'qrcode';
import { useEffect, useState } from 'react';

interface QrCodeCardProps {
  binCode: string;
  qrToken: string;
  qrPayload: string;
  issuedLabel?: string;
}

export function QrCodeCard({ binCode, qrToken, qrPayload, issuedLabel }: QrCodeCardProps) {
  const [dataUrl, setDataUrl] = useState<string>('');
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    let active = true;
    QRCode.toDataURL(qrPayload || qrToken, {
      width: 220,
      margin: 2,
      color: { dark: '#0F172A', light: '#FFFFFF' },
    })
      .then((url) => {
        if (active) setDataUrl(url);
      })
      .catch(() => {
        if (active) setDataUrl('');
      });
    return () => {
      active = false;
    };
  }, [qrPayload, qrToken]);

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(qrToken);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 1800);
    } catch {
      // ignore clipboard errors
    }
  };

  return (
    <div className="gt-page-enter flex flex-col gap-4 rounded-xl border border-emerald-100 bg-white p-5 shadow-sm sm:flex-row sm:items-center">
      <div className="flex h-36 w-36 shrink-0 items-center justify-center rounded-md border border-slate-200 bg-white p-2">
        {dataUrl ? (
          <img
            src={dataUrl}
            alt={`QR code for bin ${binCode}`}
            className="h-full w-full object-contain"
          />
        ) : (
          <span className="text-xs text-slate-400">Rendering QR…</span>
        )}
      </div>
      <div className="min-w-0 flex-1 space-y-2">
        <div className="flex flex-wrap items-center gap-2 text-xs text-slate-500">
          <span className="font-mono font-medium text-slate-900">{binCode}</span>
          {issuedLabel && (
            <>
              <span aria-hidden="true">·</span>
              <span>{issuedLabel}</span>
            </>
          )}
        </div>
        <p className="text-xs text-slate-600">
          Opaque QR credential generated by backend. Save or print now — previous credentials for this bin are revoked.
        </p>
        <div className="rounded border border-slate-200 bg-slate-50 px-3 py-2 font-mono text-xs text-slate-800 break-all">
          {qrToken}
        </div>
        <div className="flex flex-wrap items-center gap-2 pt-1">
          <button
            type="button"
            onClick={handleCopy}
            className="inline-flex items-center gap-1.5 rounded-md border border-slate-300 bg-white px-3 py-1.5 text-xs font-medium text-slate-700 transition-colors hover:bg-slate-50 whitespace-nowrap shrink-0"
          >
            {copied ? <Check className="h-3.5 w-3.5 text-[#16A34A]" /> : <Copy className="h-3.5 w-3.5" />}
            <span>{copied ? 'Token copied' : 'Copy token'}</span>
          </button>
          {dataUrl && (
            <a
              href={dataUrl}
              download={`${binCode}-qr.png`}
              className="inline-flex items-center gap-1.5 rounded-md border border-slate-300 bg-white px-3 py-1.5 text-xs font-medium text-slate-700 transition-colors hover:bg-slate-50 whitespace-nowrap shrink-0"
            >
              <Download className="h-3.5 w-3.5" />
              <span>Download QR PNG</span>
            </a>
          )}
        </div>
      </div>
    </div>
  );
}
